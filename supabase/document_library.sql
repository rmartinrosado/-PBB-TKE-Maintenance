create table if not exists public.documents (
  id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  file_name text not null,
  storage_path text not null unique,
  mime_type text,
  file_size bigint not null default 0,
  pbb_scope text not null default 'GENERAL',
  document_type text not null default 'manual',
  revision text,
  notes text,
  extracted_chars integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.document_chunks (
  id bigint generated by default as identity primary key,
  document_id uuid not null references public.documents(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  chunk_index integer not null,
  page_label text,
  content text not null,
  created_at timestamptz not null default now(),
  unique (document_id, chunk_index)
);

alter table public.documents enable row level security;
alter table public.document_chunks enable row level security;

drop policy if exists "Users manage own documents" on public.documents;
create policy "Users manage own documents"
on public.documents for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users manage own document chunks" on public.document_chunks;
create policy "Users manage own document chunks"
on public.document_chunks for all to authenticated
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.documents d
    where d.id = document_id and d.user_id = auth.uid()
  )
);

create index if not exists documents_user_created_idx
on public.documents(user_id, created_at desc);
create index if not exists document_chunks_document_idx
on public.document_chunks(document_id, chunk_index);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'pbb-private-docs',
  'pbb-private-docs',
  false,
  52428800,
  array['application/pdf','text/plain']
)
on conflict (id) do update set
  public = false,
  file_size_limit = 52428800,
  allowed_mime_types = array['application/pdf','text/plain'];

drop policy if exists "Users access own PBB documents" on storage.objects;
create policy "Users access own PBB documents"
on storage.objects for all to authenticated
using (
  bucket_id = 'pbb-private-docs'
  and (storage.foldername(name))[1] = auth.uid()::text
)
with check (
  bucket_id = 'pbb-private-docs'
  and (storage.foldername(name))[1] = auth.uid()::text
);

